class BlenderBackend:
    """Compile deterministic manifests to a self-contained Blender Python scene."""

    def __init__(self, executable: str = "blender") -> None:
        self.executable = executable

    def compile(
        self,
        manifest: SceneManifest,
        *,
        build_directory: str | Path,
        asset_paths: Mapping[str, Path] | None = None,
    ) -> tuple[Path, Path]:
        build_dir = Path(build_directory).resolve()
        build_dir.mkdir(parents=True, exist_ok=True)
        canonical_path = build_dir / "scene.manifest.canonical.json"
        canonical_path.write_text(manifest.to_canonical_json() + "\n", encoding="utf-8")
        assets = {key: str(value.resolve()) for key, value in sorted((asset_paths or {}).items())}
        script = _BLENDER_SCRIPT.replace(
            "__MANIFEST_JSON__", repr(manifest.to_canonical_json())
        ).replace("__ASSET_JSON__", repr(canonical_json(assets)))
        script_path = build_dir / "build_scene.py"
        script_path.write_text(script, encoding="utf-8", newline="\n")
        return canonical_path, script_path

    def command(
        self,
        script_path: str | Path,
        build_directory: str | Path,
        *,
        render: bool = True,
    ) -> list[str]:
        command = [
            self.executable,
            "--background",
            "--python",
            str(Path(script_path).resolve()),
            "--",
            "--build-dir",
            str(Path(build_directory).resolve()),
        ]
        if render:
            command.append("--render")
        return command

    def execute(self, command: list[str]) -> subprocess.CompletedProcess[str]:
        completed = subprocess.run(command, capture_output=True, text=True, check=False)
        if completed.returncode != 0:
            detail = completed.stderr[-4000:] if completed.stderr else completed.stdout[-4000:]
            raise RenderError(f"Blender render failed ({completed.returncode}): {detail}")
        return completed
