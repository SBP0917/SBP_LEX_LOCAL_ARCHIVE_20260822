def _claim_record(spec: Mapping[str, Any]) -> dict[str, Any]:
    return {
        "claim_id": spec["claim_id"],
        "claim_text": spec["claim_text"],
        "claim_category": spec["claim_category"],
        "claim_scope": spec["claim_scope"],
        "claim_status": CLAIM_READY_FOR_REVIEW,
        "supporting_evidence_artifacts": list(spec["supporting_evidence_artifacts"]),
        "supporting_verification_commands": list(spec["supporting_verification_commands"]),
        "expected_validation_answer": spec["expected_validation_answer"],
        "reviewer_validation_question": spec["reviewer_validation_question"],
        "exclusions": list(spec["exclusions"]),
        "notes": spec["notes"],
    }


def _command_record(spec: Mapping[str, Any]) -> dict[str, Any]:
    return {
        "command_id": spec["command_id"],
        "command": spec["command"],
        "purpose": spec["purpose"],
        "expected_result": spec["expected_result"],
        "required": True,
        "related_claim_ids": list(spec["related_claim_ids"]),
    }


